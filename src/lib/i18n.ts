/**
 * Task 50 — lightweight i18n for SmartMart POS.
 *
 * 8 languages covering the markets this POS ships to: English, Urdu, Arabic
 * (both RTL), Hindi, Bengali, Turkish, French and Spanish. Coverage focuses on
 * the highest-traffic surfaces: the app shell (navigation + account menu),
 * Dashboard, the POS terminal, the login/register screen and Settings.
 * Any string missing from a language falls back to English, so the UI can
 * never show a raw key.
 *
 * Urdu + Arabic flip the whole document to RTL via the `dir` attribute
 * (applied by applyDocumentLang — see stores/lang.ts).
 */
export type Lang = 'en' | 'ur' | 'ar' | 'hi' | 'bn' | 'tr' | 'fr' | 'es'

