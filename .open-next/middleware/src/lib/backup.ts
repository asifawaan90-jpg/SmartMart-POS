import { db } from '@/lib/db'
import type { BackupData, BackupRange, BackupTable } from '@/lib/backup-shared'

/**
 * Backup engine (server-only) — collects a complete, tenant-scoped snapshot
 * of one business.
 *
 * SECURITY: passwordHash is NEVER selected; SMTP credentials live in settings
 * and are redacted by the settings API before reaching any client.
 */

const iso = (d: Date | null | undefined) => (d ? new Date(d).toISOString() : '')

function rangeFilter(range: BackupRange): { createdAt?: { gte?: Date; lte?: Date } } {
  if (!range.from && !range.to) return {}
  return {
    createdAt: {
      ...(range.from ? { gte: new Date(`${range.from}T00:00:00.000Z`) } : {}),
      ...(range.to ? { lte: new Date(`${range.to}T23:59:59.999Z`) } : {}),
    },
  }
}

/** Collects the full snapshot for one business (tenant-scoped). */
export async function collectBackupData(businessId: string, range: BackupRange = {}): Promise<BackupData> {
  const rf = rangeFilter(range) as Record<string, unknown>

  const [business, users, categories, brands, units, products, inventoryTransactions, sales, saleReturns, purchases, purchaseReturns, customers, customerTransactions, suppliers, supplierTransactions, expenseCategories, expenses, setting] =
    await Promise.all([
      db.business.findUnique({ where: { id: businessId } }),
      db.user.findMany({
        where: { businessId },
        select: { id: true, name: true, email: true, phone: true, role: true, perms: true, isActive: true, lastLoginAt: true, createdAt: true },
        orderBy: { createdAt: 'asc' },
      }),
      db.category.findMany({ where: { businessId }, orderBy: { name: 'asc' } }),
      db.brand.findMany({ where: { businessId }, orderBy: { name: 'asc' } }),
      db.unit.findMany({ where: { businessId }, orderBy: { name: 'asc' } }),
      db.product.findMany({
        where: { businessId, ...rf },
        include: {
          category: { select: { name: true } },
          brand: { select: { name: true } },
          unit: { select: { name: true, shortName: true } },
          supplier: { select: { name: true } },
        },
        orderBy: { createdAt: 'asc' },
      }),
      db.inventoryTransaction.findMany({ where: { businessId, ...rf }, orderBy: { createdAt: 'asc' } }),
      db.sale.findMany({ where: { businessId, ...rf }, include: { customer: { select: { name: true } } }, orderBy: { createdAt: 'asc' } }),
      db.saleReturn.findMany({ where: { businessId, ...rf }, orderBy: { createdAt: 'asc' } }),
      db.purchase.findMany({ where: { businessId, ...rf }, include: { supplier: { select: { name: true } } }, orderBy: { createdAt: 'asc' } }),
      db.purchaseReturn.findMany({ where: { businessId, ...rf }, orderBy: { createdAt: 'asc' } }),
      db.customer.findMany({ where: { businessId }, orderBy: { name: 'asc' } }),
      db.customerTransaction.findMany({ where: { businessId, ...rf }, include: { customer: { select: { name: true } } }, orderBy: { createdAt: 'asc' } }),
      db.supplier.findMany({ where: { businessId }, orderBy: { name: 'asc' } }),
      db.supplierTransaction.findMany({ where: { businessId, ...rf }, include: { supplier: { select: { name: true } } }, orderBy: { createdAt: 'asc' } }),
      db.expenseCategory.findMany({ where: { businessId }, orderBy: { name: 'asc' } }),
      db.expense.findMany({ where: { businessId, ...rf }, include: { category: { select: { name: true } } }, orderBy: { expenseDate: 'asc' } }),
      db.setting.findUnique({ where: { businessId } }),
    ])

  // settings may contain SMTP credentials — redact before any export leaves the server
  let settingsObj: Record<string, unknown> = {}
  try { settingsObj = setting ? JSON.parse(setting.data) : {} } catch { settingsObj = {} }
  const smtp = settingsObj.smtp as Record<string, unknown> | undefined
  if (smtp && typeof smtp === 'object') {
    settingsObj = { ...settingsObj, smtp: { host: smtp.host || '', port: smtp.port || '', from: smtp.from || '', configured: Boolean(smtp.pass || smtp.host) } }
  }

  const data: BackupData = {
    meta: {
      app: 'SmartMart POS',
      version: '1.0',
      businessId,
      businessName: business?.name || '',
      exportedAt: new Date().toISOString(),
      range: { from: range.from, to: range.to },
      counts: {},
      note: 'Full data snapshot. User passwords are never included. Generated by SmartMart POS backup.',
    },
    business: business ? [{
      id: business.id, name: business.name, ownerName: business.ownerName, email: business.email,
      phone: business.phone, address: business.address, currency: business.currency,
      bizType: business.bizType, logo: business.logo ? '[embedded]' : '', createdAt: iso(business.createdAt),
    }] : [],
    users: users.map(u => ({ ...u, perms: JSON.stringify(u.perms || []), lastLoginAt: iso(u.lastLoginAt), createdAt: iso(u.createdAt) })),
    categories: categories.map(c => ({ id: c.id, name: c.name, createdAt: iso(c.createdAt) })),
    brands: brands.map(b => ({ id: b.id, name: b.name })),
    units: units.map(u => ({ id: u.id, name: u.name, shortName: u.shortName })),
    products: products.map(p => ({
      id: p.id, name: p.name, sku: p.sku, barcode: p.barcode, category: p.category?.name || '',
      brand: p.brand?.name || '', unit: p.unit?.shortName || p.unit?.name || '', supplier: p.supplier?.name || '',
      costPrice: p.costPrice, lastCostPrice: p.lastCostPrice, retailPrice: p.retailPrice, wholesalePrice: p.wholesalePrice,
      minPrice: p.minPrice, taxRate: p.taxRate, stock: p.stock, openingStock: p.openingStock, minStock: p.minStock,
      expiryDate: iso(p.expiryDate), isActive: p.isActive, description: p.description, createdAt: iso(p.createdAt),
    })),
    inventoryTransactions: inventoryTransactions.map(t => ({
      id: t.id, productId: t.productId, type: t.type, quantity: t.quantity,
      stockBefore: t.stockBefore, stockAfter: t.stockAfter, unitCost: t.unitCost,
      refType: t.refType, refNo: t.refNo, note: t.note, createdAt: iso(t.createdAt),
    })),
    sales: sales.map(s => ({
      id: s.id, invoiceNo: s.invoiceNo, date: iso(s.createdAt), deviceTs: iso(s.deviceTs),
      customer: s.customer?.name || 'Walk-in Customer', cashier: s.cashierName,
      subtotal: s.subtotal, discount: s.discount, tax: s.tax, total: s.total,
      paid: s.paid, due: s.dueAmount, profit: s.profit, paymentMethod: s.paymentMethod,
      status: s.status, note: s.note, clientRef: s.clientRef, deviceId: s.deviceId,
    })),
    saleItems: [] as BackupTable, // filled below
    saleReturns: saleReturns.map(r => ({
      id: r.id, saleId: r.saleId, returnNo: r.returnNo, refundMethod: r.refundMethod,
      items: r.items, total: r.total, reason: r.reason, createdAt: iso(r.createdAt),
    })),
    purchases: purchases.map(p => ({
      id: p.id, invoiceNo: p.invoiceNo, date: iso(p.createdAt), supplier: p.supplier?.name || '',
      subtotal: p.subtotal, discount: p.discount, tax: p.tax, total: p.total,
      paid: p.paid, due: p.dueAmount, status: p.status, note: p.note,
    })),
    purchaseItems: [] as BackupTable, // filled below
    purchaseReturns: purchaseReturns.map(r => ({
      id: r.id, purchaseId: r.purchaseId, returnNo: r.returnNo, items: r.items,
      total: r.total, reason: r.reason, createdAt: iso(r.createdAt),
    })),
    customers: customers.map(c => ({
      id: c.id, name: c.name, phone: c.phone, address: c.address,
      openingBalance: c.openingBalance, creditLimit: c.creditLimit,
      notes: c.notes, isActive: c.isActive, createdAt: iso(c.createdAt),
    })),
    customerTransactions: customerTransactions.map(t => ({
      id: t.id, customer: t.customer?.name || '', type: t.type, amount: t.amount,
      balanceAfter: t.balanceAfter, refNo: t.refNo, note: t.note, dueDate: iso(t.dueDate), createdAt: iso(t.createdAt),
    })),
    suppliers: suppliers.map(su => ({
      id: su.id, name: su.name, company: su.company, phone: su.phone, address: su.address,
      openingBalance: su.openingBalance, notes: su.notes, isActive: su.isActive, createdAt: iso(su.createdAt),
    })),
    supplierTransactions: supplierTransactions.map(t => ({
      id: t.id, supplier: t.supplier?.name || '', type: t.type, amount: t.amount,
      balanceAfter: t.balanceAfter, refNo: t.refNo, note: t.note, createdAt: iso(t.createdAt),
    })),
    expenseCategories: expenseCategories.map(c => ({ id: c.id, name: c.name })),
    expenses: expenses.map(x => ({
      id: x.id, date: iso(x.expenseDate), title: x.title, category: x.category?.name || '',
      amount: x.amount, paidTo: x.paidTo, paymentMethod: x.paymentMethod, note: x.note,
    })),
    settings: [{ ...settingsObj, exportedAt: new Date().toISOString() }],
  }

  // sale items need a separate query (Sale.items is a relation, not included above)
  const saleIds = sales.map(s => s.id)
  const items = saleIds.length
    ? await db.saleItem.findMany({ where: { saleId: { in: saleIds } }, orderBy: { saleId: 'asc' } })
    : []
  data.saleItems = items.map(i => ({
    id: i.id, saleId: i.saleId, product: i.name, sku: i.sku, barcode: i.barcode,
    quantity: i.quantity, price: i.price, costAtSale: i.costAtSale, discount: i.discount,
    taxRate: i.taxRate, taxAmount: i.taxAmount, total: i.total, returnedQty: i.returnedQty,
  }))

  const purchaseIds = purchases.map(p => p.id)
  const pItems = purchaseIds.length
    ? await db.purchaseItem.findMany({ where: { purchaseId: { in: purchaseIds } }, orderBy: { purchaseId: 'asc' } })
    : []
  data.purchaseItems = pItems.map(i => ({
    id: i.id, purchaseId: i.purchaseId, product: i.name, quantity: i.quantity,
    unitCost: i.unitCost, discount: i.discount, total: i.total, returnedQty: i.returnedQty,
  }))

  // fill counts into meta
  const keys = Object.keys(data).filter(k => k !== 'meta') as (keyof Omit<BackupData, 'meta'>)[]
  for (const k of keys) data.meta.counts[k] = (data[k] as BackupTable).length

  return data
}
